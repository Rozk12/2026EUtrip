export function getCityGuide(cityName: string): CityGuideData | null {
  const k = cityName.toLowerCase();
  if (k.includes("copenhagen") || k.includes("københavn") || k.includes("コペンハーゲン")) return CITY_GUIDE.copenhagen;
  if (k.includes("prague") || k.includes("prag") || k.includes("praha") || k.includes("プラハ")) return CITY_GUIDE.prague;
  if (k.includes("vienna") || k.includes("wien") || k.includes("ウィーン")) return CITY_GUIDE.vienna;
  if (k.includes("salzburg") || k.includes("ザルツブルク")) return CITY_GUIDE.salzburg;
  if (k.includes("tokyo") || k.includes("東京")) return CITY_GUIDE.tokyo;
  if (k.includes("osaka") || k.includes("大阪")) return CITY_GUIDE.osaka;
  return null;
}
